//! Inventory ACE interfaces found in the bundled and verification graph corpus.
use cdl_compat::{from_value, ReadOptions};
use cdl_model::{Annotation, BlockKind};
use serde_json::Value;
use std::{
    collections::{BTreeSet, HashMap},
    fs,
    path::Path,
};

fn inspect(value: &Value, rows: &mut BTreeSet<String>, candidates: &HashMap<String, Vec<String>>) {
    if let Some(object) = value.as_object() {
        if object.contains_key("name")
            && (object.contains_key("block_type") || object.contains_key("type"))
        {
            let document = from_value(value, ReadOptions::default()).expect("valid corpus graph");
            for class in document
                .library
                .classes
                .values()
                .filter(|class| class.kind == BlockKind::Extension)
            {
                let origin = match class.meta.annotations.get("ace:blockType") {
                    Some(Annotation::String(origin)) => origin,
                    _ => continue,
                };
                let ports = |ports: &[cdl_model::Connector]| {
                    ports
                        .iter()
                        .map(|port| format!("{}:{:?}", port.name, port.data_type))
                        .collect::<Vec<_>>()
                        .join(", ")
                };
                let parameters = class
                    .parameters
                    .iter()
                    .map(|p| p.name.as_str())
                    .collect::<Vec<_>>()
                    .join(", ");
                let short = origin.rsplit('.').next().unwrap();
                let closest = match short {
                    "Gain" => "Reals.MultiplyByParameter".into(),
                    "LimPID" => "Reals.PIDWithReset (verify legacy state semantics)".into(),
                    "Filter" => "filter composition (no same-named core class)".into(),
                    "LimRateLimiter" => "rate-limit composition (no same-named core class)".into(),
                    "Delay" => "delay composition (verify sampled/continuous semantics)".into(),
                    _ => candidates
                        .get(short)
                        .map(|classes| {
                            format!(
                                "{} (interface/parameter adaptation required)",
                                classes.join(", ")
                            )
                        })
                        .unwrap_or_else(|| "no same-named class in the pinned core".into()),
                };
                rows.insert(format!(
                    "| `{origin}` | `{}` | `{}` | `{parameters}` | {closest} |",
                    ports(&class.inputs),
                    ports(&class.outputs)
                ));
            }
            return;
        }
        for child in object.values() {
            inspect(child, rows, candidates);
        }
    } else if let Some(array) = value.as_array() {
        for child in array {
            inspect(child, rows, candidates);
        }
    }
}
fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let core: Value =
        serde_json::from_slice(&fs::read(root.join("web/public/schemas/CXF-Core.jsonld")).unwrap())
            .unwrap();
    let mut candidates: HashMap<String, Vec<String>> = HashMap::new();
    for class in core["@graph"]
        .as_array()
        .unwrap()
        .iter()
        .filter(|class| class["@type"] == "S231:ElementaryBlock")
    {
        let id = class["@id"].as_str().unwrap();
        candidates
            .entry(id.rsplit('.').next().unwrap().into())
            .or_default()
            .push(
                id.split("Buildings.Controls.OBC.CDL.")
                    .nth(1)
                    .unwrap_or(id)
                    .into(),
            );
    }
    for classes in candidates.values_mut() {
        classes.sort();
    }
    let mut rows = BTreeSet::new();
    for directory in ["web/public/examples", "verification"] {
        for entry in fs::read_dir(root.join(directory)).unwrap() {
            let path = entry.unwrap().path();
            if path.extension().and_then(|p| p.to_str()) == Some("json") {
                inspect(
                    &serde_json::from_slice::<Value>(&fs::read(path).unwrap()).unwrap(),
                    &mut rows,
                    &candidates,
                );
            }
        }
    }
    println!("# Observed ACE extension interfaces\n\nGenerated by `cargo run -p cdl-integration-tests --example extension_report --release`.\nThe source corpus is the bundled examples and verification graphs. Closest classes are\nmigration candidates, not claims of equivalent executable behavior; WP3 must verify them.\nThe five legacy families absent from the pinned core are additionally documented in README.md.\n\n| Legacy type | Inputs | Outputs | Supplied parameters | Closest standard class/composition |\n|---|---|---|---|---|");
    for row in rows {
        println!("{row}");
    }
}
