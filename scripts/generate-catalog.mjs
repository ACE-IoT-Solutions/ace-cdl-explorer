// Generate editor data from the built Rust wasm catalog. No interface lists live here.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { initSync, block_catalog } from '../web/src/wasm/ace_cdl_wasm.js'
initSync({ module: readFileSync(new URL('../web/src/wasm/ace_cdl_wasm_bg.wasm', import.meta.url)) })
const catalog = JSON.parse(block_catalog())
const presets = new Map(catalog.editor_templates.map(preset => [preset.id, preset]))
const typeOf = classId => classId.replace(/^http:\/\/data\.ashrae\.org\/S231#/, '')
const human = name => name.replace(/([a-z])([A-Z])/g, '$1 $2')
const dataType = value => typeof value === 'string' ? value : Object.values(value)[0].split('.').at(-1)
const ports = items => items.length ? items.map(p => `${p.name}: ${dataType(p.data_type)}${p.dimensions.length ? `[${p.dimensions.map(d => Object.values(d)[0]).join(', ')}]` : ''}`).join('; ') : 'None'
const definitions = Object.values(catalog.classes).map(cls => {
  const type = cls.meta.annotations['ace:blockType'] ?? typeOf(cls.id)
  const family = type.split('.').at(-1)
  const qualifier = type.includes('.Integers.') ? 'Integer' : ['Constant','Switch'].includes(family) && type.includes('.Logical.') ? 'Boolean' : ['Constant','Switch'].includes(family) && type.includes('.Reals.') ? 'Real' : ''
  return { type, title: human(cls.meta.label ?? family), qualifier, group: 'Elementary blocks',
    implemented: cls.meta.annotations['ace:implemented'], standard: cls.id.startsWith('http://data.ashrae.org/S231#'),
    description: cls.meta.description ?? 'A declared CDL block interface.', inputs: ports(cls.inputs), outputs: ports(cls.outputs),
    settings: cls.parameters.map(p => `${p.name}${p.default == null ? ' (required)' : ` = ${typeof p.default.value === 'object' ? JSON.stringify(p.default.value) : p.default.value}`}`).join('; ') || undefined }
})
for (const preset of catalog.editor_templates.filter(p => !catalog.classes[p.id])) {
  definitions.push({ type: preset.graph.block_type, title: human(preset.graph.block_type), qualifier: '', group: 'Composite building sequences', implemented: true, standard: false, description: 'Contains connected control blocks.', inputs: 'User-defined', outputs: 'User-defined' })
}
definitions.sort((a,b) => a.group < b.group ? -1 : a.group > b.group ? 1 : a.type < b.type ? -1 : a.type > b.type ? 1 : 0)
const entries = catalog.editor_templates.filter(p => p.creatable).map(({id,graph}) => ({
  type: graph.block_type, classId: id, label: graph.block_type === 'VAVBoxController' ? 'VAV template' : '',
  inputs: graph.inputs ?? [], outputs: graph.outputs ?? [], parameters: graph.parameters ?? []
})).sort((a,b) => a.type < b.type ? -1 : a.type > b.type ? 1 : 0)
const output = `// Generated by scripts/generate-catalog.mjs from Rust block_catalog(). Do not edit.
import { helpForType } from './blockHelpData'
import type { Connector, Parameter } from './types'
export interface BlockDefinition {
  type: string; title: string; group: 'Elementary blocks' | 'Composite building sequences'
  implemented: boolean; description: string; inputs: string; outputs: string
  settings?: string; equations?: string[]
}
interface CatalogRecord extends BlockDefinition { qualifier: string; standard: boolean }
const declarations = ${JSON.stringify(definitions,null,2)} as CatalogRecord[]
export const blockCatalog: BlockDefinition[] = declarations.map(item => {
  const help = helpForType(item.type)
  const title = help.title ?? item.title
  return {...item, ...help, title: item.qualifier && !title.toLowerCase().startsWith(item.qualifier.toLowerCase()) ? item.qualifier + ' ' + title : title,
    settings: item.standard ? item.settings : help.settings ?? item.settings}
})
export interface PaletteEntry { type: string; label: string; inputs: Connector[]; outputs: Connector[]; parameters: Parameter[] }
const presets = ${JSON.stringify(entries,null,2)} as Array<PaletteEntry & {classId: string}>
export const palette: PaletteEntry[] = presets.map(item => ({...item, label: item.label || blockCatalog.find(definition=>definition.type===item.type)?.title || item.type}))
`
const destination = fileURLToPath(new URL('../web/src/lib/blockCatalog.ts', import.meta.url))
if (process.argv.includes('--check')) {
  if (readFileSync(destination,'utf8') !== output) throw new Error('Generated catalog is stale; run scripts/generate-web.sh')
} else writeFileSync(destination, output)
